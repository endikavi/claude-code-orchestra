export class HookManager extends EventEmitter {
  private static instance: HookManager | null = null;
  private apiPort: number;

  private constructor() {
    super();
    this.apiPort = DASHBOARD_API_PORT;
  }

  public static getInstance(): HookManager {
    if (!HookManager.instance) {
      HookManager.instance = new HookManager();
    }
    return HookManager.instance;
  }

  /**
   * Set the API port for hook scripts
   */
  public setApiPort(port: number): void {
    this.apiPort = port;
  }

  /**
   * Get available hook templates
   */
  public getTemplates(): HookTemplate[] {
    return Object.values(HOOK_TEMPLATES);
  }

  /**
   * Get a specific template
   */
  public getTemplate(id: HookTemplateType): HookTemplate | undefined {
    return HOOK_TEMPLATES[id];
  }

  /**
   * Generate hook script content based on platform
   */
  private generateHookScript(
    eventType: HookEventType,
    instanceIdEnvVar: string
  ): { extension: string; content: string } {
    const isWindows = process.platform === 'win32';
    const apiUrl = `http://localhost:${this.apiPort}/api/hooks`;

    if (isWindows) {
      return {
        extension: '.ps1',
        content: this.generatePowerShellScript(eventType, instanceIdEnvVar, apiUrl),
      };
    } else {
      return {
        extension: '.sh',
        content: this.generateBashScript(eventType, instanceIdEnvVar, apiUrl),
      };
    }
  }

  /**
   * Generate PowerShell hook script
   */
  private generatePowerShellScript(
    eventType: HookEventType,
    instanceIdEnvVar: string,
    apiUrl: string
  ): string {
    const endpoint = this.getEndpointForEvent(eventType);

    return `# Dashboard Hook: ${eventType}
# Auto-generated by Claude Dashboard
# This script MUST always exit 0 to not block Claude CLI

try {
    $inputRaw = [Console]::In.ReadToEnd()
    $instanceId = $env:${instanceIdEnvVar}

    if (-not $instanceId) {
        exit 0
    }

    # Parse input JSON safely
    $inputData = $null
    if ($inputRaw -and $inputRaw.Trim()) {
        try {
            $inputData = $inputRaw | ConvertFrom-Json -ErrorAction SilentlyContinue
        } catch {
            $inputData = $null
        }
    }

    $body = @{
        instanceId = $instanceId
        eventType = "${eventType}"
        data = $inputData
        timestamp = [DateTimeOffset]::UtcNow.ToUnixTimeMilliseconds()
    } | ConvertTo-Json -Depth 10 -Compress

    try {
        $null = Invoke-RestMethod -Uri "${apiUrl}/${endpoint}" -Method Post -Body $body -ContentType "application/json" -TimeoutSec 5 -ErrorAction SilentlyContinue
    } catch {
        # Silently ignore network errors
    }
} catch {
    # Silently ignore all errors
}

exit 0
`;
  }

  /**
   * Generate Bash hook script
   */
  private generateBashScript(
    eventType: HookEventType,
    instanceIdEnvVar: string,
    apiUrl: string
  ): string {
    const endpoint = this.getEndpointForEvent(eventType);

    return `#!/bin/bash
# Dashboard Hook: ${eventType}
# Auto-generated by Claude Dashboard
# This script MUST always exit 0 to not block Claude CLI

# Trap all errors and exit cleanly
trap 'exit 0' ERR

INPUT=$(cat 2>/dev/null || echo '{}')
INSTANCE_ID="\${${instanceIdEnvVar}}"

if [ -z "$INSTANCE_ID" ]; then
    exit 0
fi

# Validate INPUT is valid JSON, default to null if not
if ! echo "$INPUT" | jq -e . >/dev/null 2>&1; then
    INPUT='null'
fi

TIMESTAMP=$(date +%s000 2>/dev/null || echo "0")

# Build JSON body safely using jq
BODY=$(jq -n \\
    --arg instanceId "$INSTANCE_ID" \\
    --arg eventType "${eventType}" \\
    --argjson data "$INPUT" \\
    --argjson timestamp "$TIMESTAMP" \\
    '{instanceId: $instanceId, eventType: $eventType, data: $data, timestamp: $timestamp}' 2>/dev/null)

if [ -z "$BODY" ]; then
    exit 0
fi

curl -s -X POST "${apiUrl}/${endpoint}" \\
    -H "Content-Type: application/json" \\
    -d "$BODY" \\
    --connect-timeout 5 \\
    --max-time 10 >/dev/null 2>&1 || true

exit 0
`;
  }

  /**
   * Generate pre-tool-use permission check script
   */
  private generatePermissionCheckScript(instanceIdEnvVar: string): {
    extension: string;
    content: string;
  } {
    const isWindows = process.platform === 'win32';
    const apiUrl = `http://localhost:${this.apiPort}/api/hooks/permission/check`;

    if (isWindows) {
      return {
        extension: '.ps1',
        content: `# Dashboard Permission Check Hook
# Auto-generated by Claude Dashboard
# This script MUST always exit 0 (or 2 to block) to not break Claude CLI

try {
    $inputRaw = [Console]::In.ReadToEnd()
    $instanceId = $env:${instanceIdEnvVar}

    if (-not $instanceId) {
        exit 0
    }

    # Parse input JSON safely
    $inputJson = $null
    if ($inputRaw -and $inputRaw.Trim()) {
        try {
            $inputJson = $inputRaw | ConvertFrom-Json -ErrorAction SilentlyContinue
        } catch {
            exit 0
        }
    }

    if (-not $inputJson) {
        exit 0
    }

    $body = @{
        instanceId = $instanceId
        toolName = $inputJson.tool_name
        toolInput = $inputJson.tool_input
        timestamp = [DateTimeOffset]::UtcNow.ToUnixTimeMilliseconds()
    } | ConvertTo-Json -Depth 10 -Compress

    try {
        $response = Invoke-RestMethod -Uri "${apiUrl}" -Method Post -Body $body -ContentType "application/json" -TimeoutSec 5 -ErrorAction SilentlyContinue

        if ($response.decision -eq "allow") {
            $output = @{
                hookSpecificOutput = @{
                    permissionDecision = "allow"
                    permissionDecisionReason = $response.reason
                }
            } | ConvertTo-Json -Depth 10 -Compress
            Write-Output $output
            exit 0
        }
        elseif ($response.decision -eq "deny") {
            Write-Error "Blocked by dashboard policy: $($response.reason)"
            exit 2
        }
    } catch {
        # On network error, let Claude handle permission normally
    }
} catch {
    # On any error, let Claude handle permission normally
}

exit 0
`,
      };
    } else {
      return {
        extension: '.sh',
        content: `#!/bin/bash
# Dashboard Permission Check Hook
# Auto-generated by Claude Dashboard
# This script MUST always exit 0 (or 2 to block) to not break Claude CLI

# Trap errors and exit cleanly (except exit 2 for deny)
trap 'exit 0' ERR

INPUT=$(cat 2>/dev/null || echo '{}')
INSTANCE_ID="\${${instanceIdEnvVar}}"

if [ -z "$INSTANCE_ID" ]; then
    exit 0
fi

# Validate INPUT is valid JSON
if ! echo "$INPUT" | jq -e . >/dev/null 2>&1; then
    exit 0
fi

TOOL_NAME=$(echo "$INPUT" | jq -r '.tool_name // "unknown"' 2>/dev/null)
TOOL_INPUT=$(echo "$INPUT" | jq -c '.tool_input // {}' 2>/dev/null || echo '{}')
TIMESTAMP=$(date +%s000 2>/dev/null || echo "0")

# Build JSON body safely using jq
BODY=$(jq -n \\
    --arg instanceId "$INSTANCE_ID" \\
    --arg toolName "$TOOL_NAME" \\
    --argjson toolInput "$TOOL_INPUT" \\
    --argjson timestamp "$TIMESTAMP" \\
    '{instanceId: $instanceId, toolName: $toolName, toolInput: $toolInput, timestamp: $timestamp}' 2>/dev/null)

if [ -z "$BODY" ]; then
    exit 0
fi

RESPONSE=$(curl -s -X POST "${apiUrl}" \\
    -H "Content-Type: application/json" \\
    -d "$BODY" \\
    --connect-timeout 5 \\
    --max-time 10 2>/dev/null || echo '')

if [ -n "$RESPONSE" ]; then
    DECISION=$(echo "$RESPONSE" | jq -r '.decision // empty' 2>/dev/null)
    REASON=$(echo "$RESPONSE" | jq -r '.reason // empty' 2>/dev/null)

    if [ "$DECISION" = "allow" ]; then
        jq -n --arg reason "$REASON" '{hookSpecificOutput:{permissionDecision:"allow",permissionDecisionReason:$reason}}'
        exit 0
    elif [ "$DECISION" = "deny" ]; then
        echo "Blocked by dashboard policy: $REASON" >&2
        exit 2
    fi
fi

exit 0
`,
      };
    }
  }

  /**
   * Get API endpoint for event type
   */
  private getEndpointForEvent(eventType: HookEventType): string {
    switch (eventType) {
      case 'Notification':
        return 'notify';
      case 'PreToolUse':
        return 'pre-tool';
      case 'PostToolUse':
        return 'post-tool';
      case 'Stop':
      case 'SubagentStop':
        return 'stopped';
      case 'SessionStart':
        return 'session-start';
      case 'SessionEnd':
        return 'session-end';
      case 'UserPromptSubmit':
        return 'prompt-submit';
      default:
        return 'event';
    }
  }

  /**
   * Setup hooks for a project
   */
  public async setupHooksForProject(
    projectPath: string,
    settings: DashboardHookSettings,
    templateId?: HookTemplateType
  ): Promise<{ success: boolean; error?: string }> {
    try {
      const claudeDir = path.join(projectPath, '.claude');
      const hooksDir = path.join(claudeDir, 'hooks');
      const settingsPath = path.join(claudeDir, 'settings.json');

      // Create directories
      await fs.promises.mkdir(hooksDir, { recursive: true });

      // Load existing settings or create new
      let existingSettings: Record<string, unknown> = {};
      try {
        const content = await fs.promises.readFile(settingsPath, 'utf-8');
        existingSettings = JSON.parse(content);
      } catch {
        // File doesn't exist, start fresh
      }

      // Build hooks configuration
      const hooksConfig: HooksConfig = { hooks: {} };
      const instanceIdEnvVar = 'CLAUDE_DASHBOARD_INSTANCE_ID';

      // Get template if specified
      const template = templateId ? HOOK_TEMPLATES[templateId] : null;
      const effectiveSettings = template ? { ...settings, ...template.settings } : settings;

      // Create hook scripts and config based on settings
      const hookScriptsToCreate: { eventType: HookEventType; filename: string }[] = [];

      if (effectiveSettings.enableNotifications) {
        hookScriptsToCreate.push({ eventType: 'Notification', filename: 'notify' });
      }

      if (effectiveSettings.enableToolTracking) {
        hookScriptsToCreate.push({ eventType: 'PostToolUse', filename: 'post-tool' });
      }

      if (effectiveSettings.enableMetrics) {
        hookScriptsToCreate.push({ eventType: 'Stop', filename: 'stop' });
        hookScriptsToCreate.push({ eventType: 'SessionStart', filename: 'session-start' });
        hookScriptsToCreate.push({ eventType: 'SessionEnd', filename: 'session-end' });
      }

      // Generate and write hook scripts
      for (const hook of hookScriptsToCreate) {
        const script = this.generateHookScript(hook.eventType, instanceIdEnvVar);
        const scriptPath = path.join(hooksDir, `${hook.filename}${script.extension}`);

        await fs.promises.writeFile(scriptPath, script.content, { mode: 0o755 });

        // Add to hooks config
        const command =
          process.platform === 'win32'
            ? `powershell -ExecutionPolicy Bypass -File "${scriptPath}"`
            : scriptPath;

        hooksConfig.hooks[hook.eventType] = [
          {
            hooks: [{ type: 'command', command }],
          },
        ];
      }

      // Add permission check hook if enabled
      if (effectiveSettings.enablePermissionCheck) {
        const permScript = this.generatePermissionCheckScript(instanceIdEnvVar);
        const permScriptPath = path.join(hooksDir, `pre-tool${permScript.extension}`);

        await fs.promises.writeFile(permScriptPath, permScript.content, { mode: 0o755 });

        const command =
          process.platform === 'win32'
            ? `powershell -ExecutionPolicy Bypass -File "${permScriptPath}"`
            : permScriptPath;

        hooksConfig.hooks.PreToolUse = [
          {
            hooks: [{ type: 'command', command }],
          },
        ];
      }

      // Merge with existing settings
      const mergedSettings = {
        ...existingSettings,
        hooks: hooksConfig.hooks,
        dashboardIntegration: {
          enabled: effectiveSettings.enabled,
          templateId: templateId || 'custom',
          settings: effectiveSettings,
          configuredAt: Date.now(),
        },
      };

      // Write settings file
      await fs.promises.writeFile(settingsPath, JSON.stringify(mergedSettings, null, 2), 'utf-8');

      console.log(`[HookManager] Hooks configured for project: ${projectPath}`);
      this.emit('hooks:configured', { projectPath, settings: effectiveSettings, templateId });

      return { success: true };
    } catch (error) {
      const errorMessage = error instanceof Error ? error.message : 'Unknown error';
      console.error(`[HookManager] Failed to setup hooks: ${errorMessage}`);
      return { success: false, error: errorMessage };
    }
  }

  /**
   * Remove hooks from a project
   */
  public async removeHooksFromProject(
    projectPath: string
  ): Promise<{ success: boolean; error?: string }> {
    try {
      const claudeDir = path.join(projectPath, '.claude');
      const hooksDir = path.join(claudeDir, 'hooks');
      const settingsPath = path.join(claudeDir, 'settings.json');

      // Remove hooks directory
      try {
        await fs.promises.rm(hooksDir, { recursive: true, force: true });
      } catch {
        // Directory might not exist
      }

      // Update settings to remove hooks
      try {
        const content = await fs.promises.readFile(settingsPath, 'utf-8');
        const settings = JSON.parse(content);

        delete settings.hooks;
        delete settings.dashboardIntegration;

        await fs.promises.writeFile(settingsPath, JSON.stringify(settings, null, 2), 'utf-8');
      } catch {
        // Settings file might not exist
      }

      console.log(`[HookManager] Hooks removed from project: ${projectPath}`);
      this.emit('hooks:removed', { projectPath });

      return { success: true };
    } catch (error) {
      const errorMessage = error instanceof Error ? error.message : 'Unknown error';
      console.error(`[HookManager] Failed to remove hooks: ${errorMessage}`);
      return { success: false, error: errorMessage };
    }
  }

  /**
   * Check if a project has dashboard hooks configured
   */
  public async hasHooksConfigured(projectPath: string): Promise<boolean> {
    try {
      const settingsPath = path.join(projectPath, '.claude', 'settings.json');
      const content = await fs.promises.readFile(settingsPath, 'utf-8');
      const settings = JSON.parse(content);

      return settings.dashboardIntegration?.enabled === true;
    } catch {
      return false;
    }
  }

  /**
   * Get hook settings for a project
   */
  public async getProjectHookSettings(projectPath: string): Promise<DashboardHookSettings | null> {
    try {
      const settingsPath = path.join(projectPath, '.claude', 'settings.json');
      const content = await fs.promises.readFile(settingsPath, 'utf-8');
      const settings = JSON.parse(content);

      return settings.dashboardIntegration?.settings || null;
    } catch {
      return null;
    }
  }

  /**
   * Destroy the hook manager
   */
  public destroy(): void {
    HookManager.instance = null;
  }
}

// Export singleton getter
export function getHookManager(): HookManager {
  return HookManager.getInstance();
}
